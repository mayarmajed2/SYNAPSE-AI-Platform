import io
import zipfile
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import Response
from sqlalchemy.orm import Session

from app.db.database import get_db
from app.db.models import Artifact, Project
from app.schemas.artifact import ArtifactCreate, ArtifactResponse, ArtifactTreeItem

router = APIRouter(prefix="/artifacts", tags=["Artifacts"])


@router.get("/project/{project_id}", response_model=List[ArtifactResponse])
def list_project_artifacts(
    project_id: str,
    artifact_type: Optional[str] = Query(None),
    db: Session = Depends(get_db),
):
    """List all generated files and specifications for a project."""
    query = db.query(Artifact).filter(Artifact.project_id == project_id, Artifact.is_current == True)
    if artifact_type:
        query = query.filter(Artifact.artifact_type == artifact_type)

    return query.order_by(Artifact.file_path.asc()).all()


@router.get("/project/{project_id}/tree", response_model=List[ArtifactTreeItem])
def get_project_file_tree(project_id: str, db: Session = Depends(get_db)):
    """Retrieve file tree hierarchy of generated codebase."""
    artifacts = db.query(Artifact).filter(Artifact.project_id == project_id, Artifact.is_current == True).all()
    return [
        ArtifactTreeItem(
            id=a.id,
            file_path=a.file_path,
            file_name=a.file_name,
            artifact_type=a.artifact_type,
            language=a.language,
            size_bytes=a.size_bytes,
            updated_at=a.updated_at,
        )
        for a in artifacts
    ]


@router.get("/{artifact_id}", response_model=ArtifactResponse)
def get_artifact(artifact_id: str, db: Session = Depends(get_db)):
    """Retrieve full content and metadata of a specific file or artifact."""
    artifact = db.query(Artifact).filter(Artifact.id == artifact_id).first()
    if not artifact:
        raise HTTPException(status_code=404, detail="Artifact not found")
    return artifact


@router.post("", response_model=ArtifactResponse)
def create_artifact(data: ArtifactCreate, db: Session = Depends(get_db)):
    """Register or version an artifact generated by an agent."""
    artifact = Artifact(
        project_id=data.project_id,
        task_id=data.task_id,
        file_path=data.file_path,
        file_name=data.file_name,
        artifact_type=data.artifact_type,
        content=data.content,
        language=data.language,
        version=data.version,
        size_bytes=len(data.content.encode("utf-8")),
        is_current=True,
    )
    db.add(artifact)
    db.commit()
    db.refresh(artifact)
    return artifact


@router.get("/project/{project_id}/download")
def download_project_artifacts(project_id: str, db: Session = Depends(get_db)):
    """Download the complete generated project codebase as a ZIP archive."""
    project = db.query(Project).filter(Project.id == project_id).first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    artifacts = db.query(Artifact).filter(Artifact.project_id == project_id, Artifact.is_current == True).all()
    if not artifacts:
        raise HTTPException(status_code=404, detail="No artifacts generated yet for this project")

    zip_buffer = io.BytesIO()
    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
        for art in artifacts:
            clean_path = art.file_path.lstrip("/\\")
            zip_file.writestr(clean_path, art.content)

    zip_buffer.seek(0)
    filename = f"{project.slug}-codebase.zip"
    return Response(
        content=zip_buffer.getvalue(),
        media_type="application/zip",
        headers={"Content-Disposition": f"attachment; filename={filename}"},
    )

